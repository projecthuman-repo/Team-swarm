#!/usr/bin/env bash
# Footprint report (Lean & Precise L0.1): wheel sizes per requirement set,
# plus — when a container runtime is up — the size of every swarm image,
# runtime disk usage, and the SLA latency lines. `make footprint` runs it;
# the first run is committed as docs/footprint-baseline.md.
set -uo pipefail
cd "$(dirname "$0")/.."

PY="${PYTHON:-python3}"
RUNTIME="$(command -v podman || command -v docker || true)"

echo "# Footprint report"
echo
python3 - <<'EOF' 2>/dev/null || true
import subprocess
rev = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
print(f"Tree `{rev}` — generated by `scripts/footprint_report.sh` (`make footprint`).")
EOF
echo
"$PY" scripts/footprint_wheels.py
echo

echo "## Container images"
echo
if [ -n "$RUNTIME" ] && "$RUNTIME" info >/dev/null 2>&1; then
  echo "| image | size (bytes) |"
  echo "|---|---:|"
  "$RUNTIME" images --format '{{.Repository}}:{{.Tag}}' \
    | grep -Ei 'swarm|deploy[-_]|team-swarm' \
    | while read -r img; do
        printf '| `%s` | %s |\n' "$img" "$("$RUNTIME" image inspect --format '{{.Size}}' "$img")"
      done
  echo
  echo '```'
  "$RUNTIME" system df
  echo '```'
  echo
  echo "## SLA latency lines"
  echo
  echo '```'
  make -s sla 2>/dev/null | grep -Ei 'latency|p95' || echo "(spine not running)"
  echo '```'
else
  echo "_No running container runtime in this environment — image sizes, disk"
  echo "usage and SLA latency come from \`make verify-integration\` on the runtime host._"
fi

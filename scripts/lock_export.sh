#!/usr/bin/env bash
# `make lock` (Lean & Precise L1.1): re-lock, then regenerate every
# requirements*.txt from uv.lock. pyproject.toml + uv.lock are the source of
# truth; the requirements files are generated artifacts for the pip fallback.
# Idempotent: a second run produces no diff.
set -euo pipefail
cd "$(dirname "$0")/.."
export UV_PYTHON="${UV_PYTHON:-3.12}"

HEADER='# GENERATED by make lock from pyproject.toml/uv.lock — do not edit'
EXPORT=(uv export --frozen --no-header --no-hashes --no-annotate)

uv lock

emit() { # $1 = target file, $2 = provenance line; body on stdin
  { echo "$HEADER"; echo "# $2"; cat; } > "$1.tmp" && mv "$1.tmp" "$1"
}

base() { "${EXPORT[@]}" --no-default-groups; }

# uv 0.11 has no --only-extra: export base+extra and drop every package the
# base closure already pins. Pins come from the same lock, so the add-on set
# is consistent with requirements.txt (DECISIONS D-012).
only_extra() {
  local names
  names="$(mktemp)"
  base | sed -E 's/[=<>!~ ;].*//' | tr 'A-Z' 'a-z' > "$names"
  "${EXPORT[@]}" --no-default-groups --extra "$1" \
    | awk 'NR==FNR { seen[$0] = 1; next }
           { n = tolower($0); sub(/[=<>!~ ;].*/, "", n); if (!(n in seen)) print }' "$names" -
  rm -f "$names"
}

"${EXPORT[@]}" --no-dev --group agent \
  | emit requirements.txt "uv export --no-dev --group agent (agent image: base + aider)"
"${EXPORT[@]}" --only-group dev \
  | emit requirements-dev.txt "uv export --only-group dev"
"${EXPORT[@]}" --only-group ingest \
  | emit requirements-ingest.txt "uv export --only-group ingest (ingest image; never with the agent group)"

{ echo "# torch-based option: uv sync --extra embeddings-torch (sentence-transformers)."
  only_extra embeddings; } \
  | emit requirements-embeddings.txt "only extra 'embeddings' (fastembed, no torch) — add-on to requirements.txt"
for extra in vector orchestration routing ccompat; do
  only_extra "$extra" | emit "requirements-$extra.txt" "only extra '$extra' — add-on to requirements.txt"
done

emit requirements-elevation.txt "no packages: the v4.1 elevation set moved (Lean & Precise L1.1)" <<'EOF'
#   psutil, nvidia-ml-py -> base dependencies ([project.dependencies], requirements.txt)
#   headroom-ai          -> the `ingest` group (requirements-ingest.txt,
#                           deploy/Containerfile.ingest) and `make tools`
#   litellm              -> the litellm gateway container (compose profile `litellm`)
# Installing this file is a no-op; it is kept so existing commands still work.
EOF

echo "lock: uv.lock + $(ls requirements*.txt | wc -l) requirements files regenerated"
